#!/usr/bin/env python3
"""Generate docs/taxonomy/ASI-MAPPING.md and docs/taxonomy/TAXONOMY.md from taxonomy/asi-mapping.yaml.

    python scripts/gen_taxonomy_docs.py          # rewrite both pages
    python scripts/gen_taxonomy_docs.py --check  # exit 1 if either page is stale
    python scripts/gen_taxonomy_docs.py --missing  # YAML stubs for registered checks that have no mapping yet

The YAML is the source of truth. tests/test_asi_mapping.py fails when a registered check is missing from it
and when the generated pages are out of date.
"""
# Ref: [OWASP-AgenticTop10-2026] (ASI IDs and titles; CC BY-SA 4.0). The assignment of agentest checks to them is this project's own judgement.

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MAPPING = ROOT / "taxonomy" / "asi-mapping.yaml"
OUT_MAP = ROOT / "docs" / "taxonomy" / "ASI-MAPPING.md"
OUT_TAX = ROOT / "docs" / "taxonomy" / "TAXONOMY.md"
TIER_LABEL = {"core": "core (165 tests)", "opt-in": "opt-in New test", "pack": "extension pack"}


def load() -> dict:
    return yaml.safe_load(MAPPING.read_text(encoding="utf-8"))


def check_key(i: str) -> tuple:
    prefix, _, n = i.partition("-")
    family = ("T", "X", "NT", "BF", "DL", "EX", "MA", "PV", "RT")
    if prefix.startswith("T") and prefix[1:].isdigit():
        return (0, int(prefix[1:]), int(n))
    return (1 + (family.index(prefix) if prefix in family else len(family)), 0, int(n))


def _row(i: str, e: dict) -> str:
    asi = ", ".join(f"{a['id']}{'' if a['fit'] == 'direct' else ' (partial)'}" for a in e["asi"]) or "no ASI mapping"
    tier = TIER_LABEL[e["tier"]] + (f": {e['pack']}" if e.get("pack") else "")
    return f"| `{i}` | {e['title'].replace('|', '/')} | {tier} | {e['category']} | {asi} |"


def coverage(m: dict) -> dict:
    asi = m["asi"]
    cov = {a: Counter() for a in asi}
    for e in m["checks"].values():
        for a in e["asi"]:
            cov[a["id"]][a["fit"]] += 1
            cov[a["id"]]["core" if e["tier"] == "core" else "other"] += 1
    return cov


def totals(m: dict) -> dict:
    tiers = Counter(e["tier"] for e in m["checks"].values())
    mapped = Counter(e["tier"] for e in m["checks"].values() if e["status"] == "mapped")
    return {"all": len(m["checks"]), "mapped": sum(mapped.values()), "tiers": tiers, "mapped_by_tier": mapped}


def build_mapping_page(m: dict) -> str:
    src = m["source"]
    t = totals(m)
    cov = coverage(m)
    L: list[str] = []
    L.append("# Check to OWASP Agentic Top 10 mapping (taxonomy v0.1)")
    L.append("")
    L.append("<!-- Generated by scripts/gen_taxonomy_docs.py from taxonomy/asi-mapping.yaml. Do not edit by hand. -->")
    L.append("")
    L.append("Which **AiEnsured agentest, an Agentic AI Testing platform** check guards against which entry of the OWASP Top 10 for Agentic Applications (ASI01 to ASI10). "
             "The machine-readable source is [`taxonomy/asi-mapping.yaml`](../../taxonomy/asi-mapping.yaml). "
             "The failure categories the checks are grouped into are in the [taxonomy](TAXONOMY.md).")
    L.append("")
    L.append("**Read this first.** This is an informal crosswalk for orientation. It is not a compliance claim, an audit result or a certification statement, "
             "and a passing run does not make a system safe against an ASI entry. "
             f"The ASI IDs and titles are quoted from the OWASP document below ({src['licence']}). The assignment of checks to them is this project's own judgement, "
             "OWASP has not reviewed or endorsed it, and corrections are welcome by pull request.")
    L.append("")
    L.append("## Source")
    L.append("")
    L.append(f"- {src['name']}.")
    L.append(f"- Page: <{src['url']}>")
    L.append(f"- Document: <{src['document_url']}>")
    L.append(f"- Fetched: {src['fetched']}. If OWASP revises the list, this mapping is revisited and the taxonomy version is bumped.")
    L.append("")
    L.append("## How a check is mapped")
    L.append("")
    for k, v in m["fit_values"].items():
        L.append(f"- **{k}**: {v}")
    L.append("- **no ASI mapping**: the check does not fit any entry, so it is left unmapped with a reason. Nothing is forced into an entry to raise the count.")
    L.append("")
    L.append(f"A secondary [NIST AI RMF](https://www.nist.gov/itl/ai-risk-management-framework) function tag (GOVERN, MANAGE or MEASURE) is given per failure category where one is clear. {m['nist_ai_rmf_note']}")
    L.append("")
    L.append("## Coverage")
    L.append("")
    c_core = t["tiers"]["core"]
    L.append(f"All {t['all']} registered checks were assessed: the {c_core} core tests, {t['tiers']['opt-in']} opt-in New tests (outside the 165) and {t['tiers']['pack']} checks in the opt-in extension packs. "
             f"{t['mapped']} have at least one ASI entry and {t['all'] - t['mapped']} have no ASI mapping.")
    L.append("")
    L.append("| Set | Checks | Mapped to an ASI entry | No ASI mapping |")
    L.append("|---|---|---|---|")
    for tier in ("core", "opt-in", "pack"):
        n, mp = t["tiers"][tier], t["mapped_by_tier"][tier]
        L.append(f"| {TIER_LABEL[tier]} | {n} | {mp} | {n - mp} |")
    L.append(f"| all | {t['all']} | {t['mapped']} | {t['all'] - t['mapped']} |")
    L.append("")
    L.append("Checks per ASI entry (a check can map to more than one):")
    L.append("")
    L.append("| ASI | Title | Direct | Partial | Checks | of which core | of which opt-in or pack |")
    L.append("|---|---|---|---|---|---|---|")
    for a, title in m["asi"].items():
        c = cov[a]
        L.append(f"| {a} | {title} | {c['direct']} | {c['partial']} | {c['direct'] + c['partial']} | {c['core']} | {c['other']} |")
    L.append("")
    thin = [a for a in m["asi"] if cov[a]["direct"] == 0]
    if thin:
        L.append("Entries with no direct check: " + ", ".join(f"{a} ({m['asi'][a]})" for a in thin) + ". "
                 "These are coverage gaps in agentest, not a statement that the risk is absent. [Contributions are welcome](../../CONTRIBUTING.md#add-a-check-or-a-test-case).")
        L.append("")
    L.append("## Checks by ASI entry")
    L.append("")
    by_asi: dict[str, list[str]] = defaultdict(list)
    for i, e in m["checks"].items():
        for a in e["asi"]:
            by_asi[a["id"]].append(i)
    for a, title in m["asi"].items():
        ids = sorted(by_asi[a], key=check_key)
        L.append(f"### {a}: {title}")
        L.append("")
        if not ids:
            L.append("No check is mapped to this entry yet.")
            L.append("")
            continue
        L.append("| Check | What it checks | Set | Fit |")
        L.append("|---|---|---|---|")
        for i in ids:
            e = m["checks"][i]
            fit = next(x["fit"] for x in e["asi"] if x["id"] == a)
            tier = TIER_LABEL[e["tier"]] + (f": {e['pack']}" if e.get("pack") else "")
            L.append(f"| `{i}` | {e['title'].replace('|', '/')} | {tier} | {fit} |")
        L.append("")
    L.append("## Checks with no ASI mapping")
    L.append("")
    L.append("These guard reliability, privacy, fairness or transparency properties that the Agentic Top 10 does not name. They are still part of the taxonomy (see the category column).")
    L.append("")
    L.append("| Check | What it checks | Category | Why no ASI entry fits |")
    L.append("|---|---|---|---|")
    for i in sorted((k for k, e in m["checks"].items() if e["status"] != "mapped"), key=check_key):
        e = m["checks"][i]
        L.append(f"| `{i}` | {e['title'].replace('|', '/')} | {e['category']} | {e['reason'].replace('|', '/')} |")
    L.append("")
    L.append("## Full table")
    L.append("")
    L.append("| Check | What it checks | Set | Category | ASI |")
    L.append("|---|---|---|---|---|")
    for i in sorted(m["checks"], key=check_key):
        L.append(_row(i, m["checks"][i]))
    L.append("")
    return "\n".join(L)


def build_taxonomy_page(m: dict) -> str:
    cats = m["categories"]
    by_cat: dict[str, list[str]] = defaultdict(list)
    for i, e in m["checks"].items():
        by_cat[e["category"]].append(i)
    L: list[str] = []
    L.append("# Agent failure taxonomy v0.1")
    L.append("")
    L.append("<!-- Generated by scripts/gen_taxonomy_docs.py from taxonomy/asi-mapping.yaml. Do not edit by hand. -->")
    L.append("")
    L.append("A shared vocabulary for how an AI agent fails, built from what the **AiEnsured agentest, an Agentic AI Testing platform** checks can observe in a recorded trace. "
             "It has twelve categories. Every registered check sits in exactly one category and may also point to OWASP Top 10 for Agentic Applications entries "
             "([mapping](ASI-MAPPING.md)).")
    L.append("")
    L.append("This is version **0.1**, a draft for comment. It is not a standard, and it has not been reviewed or endorsed by any standards body. "
             "Propose changes with an issue labelled `taxonomy` or a pull request; see [CONTRIBUTING](../../CONTRIBUTING.md).")
    L.append("")
    L.append("## Categories")
    L.append("")
    L.append("| ID | Category | What goes wrong | Checks | OWASP ASI entries touched |")
    L.append("|---|---|---|---|---|")
    for k, v in cats.items():
        asis = sorted({a["id"] for i in by_cat[k] for a in m["checks"][i]["asi"]})
        L.append(f"| {k} | {v['title']} | {v['definition']} | {len(by_cat[k])} | {', '.join(asis) or 'none'} |")
    L.append("")
    L.append("## Stable IDs")
    L.append("")
    L.append("| Kind | Form | Rule |")
    L.append("|---|---|---|")
    L.append("| Category | `AFC-NN` | Never reused or renumbered. A category that is retired stays listed as retired, and its checks move to a new category in a minor version. |")
    L.append("| Check | existing IDs (`T4-003`, `X-019`, `NT-038`, `PV-004`) | Unchanged. This taxonomy only groups them. |")
    L.append("| Registry entry | `AFR-NNNN` | One ID per reproducible failure, issued in order (AFR-0001, AFR-0002, and so on), never reused, even if an entry is withdrawn. The entry file name is its ID. |")
    L.append("| OWASP entry | `ASI01` to `ASI10` | Quoted from the OWASP document named in the [mapping](ASI-MAPPING.md). |")
    L.append("")
    L.append("Versioning: patch releases fix wording and mapping errors, a minor release adds or splits categories (IDs are only ever added), a major release is reserved for a change to what a category means.")
    L.append("")
    L.append("## Checks by category")
    L.append("")
    for k, v in cats.items():
        ids = sorted(by_cat[k], key=check_key)
        L.append(f"### {k}: {v['title']}")
        L.append("")
        L.append(v["definition"])
        L.append("")
        L.append("| Check | What it checks | Set | ASI |")
        L.append("|---|---|---|---|")
        for i in ids:
            e = m["checks"][i]
            asi = ", ".join(f"{a['id']}{'' if a['fit'] == 'direct' else ' (partial)'}" for a in e["asi"]) or "no ASI mapping"
            tier = TIER_LABEL[e["tier"]] + (f": {e['pack']}" if e.get("pack") else "")
            L.append(f"| `{i}` | {e['title'].replace('|', '/')} | {tier} | {asi} |")
        L.append("")
    L.append("## What this taxonomy leaves out")
    L.append("")
    L.append("- It groups agentest's checks. A failure no check can observe from a trace has no category here until a check exists. Proposals are welcome: see [submit a reproducible agent failure](../../CONTRIBUTING.md#submit-a-reproducible-agent-failure).")
    L.append("- Category sizes reflect how many checks exist, not how common or severe a failure is.")
    L.append("- Where a category touches an OWASP entry, the link is a pointer, not a claim of coverage.")
    L.append("")
    return "\n".join(L)


def registered_checks() -> dict[str, tuple[str, str | None, str]]:
    """Every registered check: ID -> (tier, pack, title). Core is the published 165 tests."""
    sys.path.insert(0, str(ROOT / "src"))
    from agentest.standards import catalog as c
    from agentest.standards import packs, rules

    nt = c.new_tests()
    core = set(c.ALL_IDS) | set(c.RAI_ADDITION_IDS) | {i for i in nt if i <= "NT-030"}
    titles = {}
    for f in (ROOT / "catalog" / "checklist-110.jsonl", ROOT / "catalog" / "rai-additions-v1.4.0.jsonl"):
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                titles[r["id"]] = r["title"]
    titles.update({i: r["title"] for i, r in nt.items()})
    titles.update({i: w.split(". ")[0].rstrip(".") for i, w in c.X_WHAT.items()})
    out: dict[str, tuple[str, str | None, str]] = {}
    for i in rules.RULES:
        out[i] = ("core" if i in core else "opt-in", None, titles.get(i, ""))
    for name, ids in packs.known_packs().items():
        if name in ("packs", "rai"):
            continue
        for i in ids:
            out[i] = ("pack", name, packs.rows()[i]["title"] if i in packs.rows() else "")
    return out


def print_missing() -> int:
    """Print YAML stubs for registered checks that are not in the mapping yet."""
    m = load()
    missing = [i for i in registered_checks() if i not in m["checks"]]
    for i in sorted(missing, key=check_key):
        tier, pack, title = registered_checks()[i]
        print(f"  {i}:")
        print(f"    title: {title}")
        print(f"    tier: {tier}")
        if pack:
            print(f"    pack: {pack}")
        print("    category: AFC-??   # one of the categories in this file")
        print("    asi: []            # [{id: ASI02, fit: direct}] or leave empty")
        print("    status: no ASI mapping   # or: mapped (and delete the reason line)")
        print("    reason: why no OWASP Agentic Top 10 entry fits")
    if not missing:
        print("every registered check is in taxonomy/asi-mapping.yaml")
    return 1 if missing else 0


def render() -> dict[Path, str]:
    m = load()
    return {OUT_MAP: build_mapping_page(m), OUT_TAX: build_taxonomy_page(m)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--missing", action="store_true", help="print YAML stubs for registered checks that are not in the mapping")
    a = ap.parse_args()
    if a.missing:
        return print_missing()
    pages = render()
    stale = [p for p, text in pages.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if a.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}; run python scripts/gen_taxonomy_docs.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in pages.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
