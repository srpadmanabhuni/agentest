"""Defect-injection self-test over the bundled reference agents (v4.0 r10).

For every agent without seeded defects: inject each generic mutation (agentest.standards.inject) into the first run it
applies to and record which checks newly fail. Judge off (deterministic). Writes a Markdown table.
Usage: python scripts/inject_selftest.py [--md docs/standards/DEFECT-INJECTION.md] [--agents DIR]"""
import argparse
import json
from pathlib import Path

from agentest.standards import judge as J
from agentest.standards import metadata, runner
from agentest.standards.inject import MUTATIONS, self_test

SEEDED = "urn:agentest:a2a-ext:seeded-defects:v1"


def seeded(a) -> bool:
    return any(e.get("uri") == SEEDED and (e.get("params") or {}).get("catalogueIds")
               for e in ((a.card.get("capabilities") or {}).get("extensions") or []))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", default=None)
    ap.add_argument("--agents", default=None)
    ap.add_argument("--all", action="store_true", help="include agents with seeded defects")
    a = ap.parse_args()
    J.configure("off")
    J.configure2("off")
    rows, tot = [], {m: [0, 0] for m in MUTATIONS}
    for name, ag in sorted(metadata.load_all(Path(a.agents) if a.agents else None).items()):
        if seeded(ag) and not a.all:
            continue
        rs = runner.runs(ag)
        if not rs:
            continue
        res = self_test(ag, rs)
        cells = []
        for m in MUTATIONS:
            v = res[m]
            if v is None:
                cells.append("—")
                continue
            tot[m][1] += 1
            tot[m][0] += bool(v["caught_by"])
            cells.append(", ".join(v["caught_by"][:4]) or "**missed**")
        rows.append(f"| {name} | " + " | ".join(cells) + " |")
    head = ("# Defect-injection self-test (generated by scripts/inject_selftest.py)\n\n"
            "Clean reference traces (agents without seeded defects); one generic defect injected per row and column; "
            "judge off. A cell lists the checks that fail only after the injection; — = nothing to mutate.\n\n"
            "| agent | " + " | ".join(MUTATIONS) + " |\n|---|" + "---|" * len(MUTATIONS) + "\n")
    summ = "\n\n" + "\n".join(f"- {m}: caught {c} of {n}" for m, (c, n) in tot.items()) + "\n"
    text = head + "\n".join(rows) + summ
    if a.md:
        Path(a.md).write_text(text)
    print(summ.strip())
    print(json.dumps({m: c for m, c in tot.items()}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
