"""Inventory of the synthetic conformance fixtures.

Prints, for each in-scope test id, how many fixtures it has and which dialects,
vocabularies and languages those fixtures cover. Writes that inventory into
docs/COVERAGE.md (appended to the reference-agent table).

    python scripts/conformance_coverage.py
    python scripts/conformance_coverage.py --check
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tests.fixtures.w10_conformance.suite import coverage_rows  # noqa: E402

OUT = ROOT / "docs" / "COVERAGE.md"


def section_lines() -> list[str]:
    rows = coverage_rows()
    lines = [
        "## Synthetic conformance fixtures",
        "",
        "Generated by `python scripts/conformance_coverage.py` from `tests/fixtures/w10_conformance/`.",
        "Unreleased r13. The package version is unchanged and detector logic is unchanged.",
        "Each in-scope test has synthetic fixtures in two tool vocabularies (shelf, clinic) and two trace dialects "
        "(native OTLP, and a LangGraph message-list import). Language-sensitive checks also use Hindi and Tamil. "
        "The counts below are an inventory of those fixtures.",
        "",
        "| Test | Fixtures | Dialects | Vocabularies | Languages |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['test']} | {row['fixtures']} | {', '.join(row['dialects'])} | "
            f"{', '.join(row['vocabularies'])} | {', '.join(row['languages'])} |"
        )
    lines.append("")
    lines.append(f"{sum(row['fixtures'] for row in rows)} synthetic fixtures across {len(rows)} in-scope tests.")
    lines.append("")
    return lines


def render_section() -> str:
    return "\n".join(section_lines()).strip() + "\n"


def _full_document() -> str:
    import importlib.util

    path = ROOT / "scripts" / "coverage_table.py"
    spec = importlib.util.spec_from_file_location("coverage_table", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.render(*mod.compute())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if docs/COVERAGE.md is missing this inventory")
    ap.add_argument("--print-only", action="store_true", help="print the inventory and do not write docs/COVERAGE.md")
    args = ap.parse_args()
    text = render_section()
    print(text, end="")
    if args.print_only:
        return 0
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if text.strip() not in current:
            print("docs/COVERAGE.md is missing the synthetic conformance inventory", file=sys.stderr)
            return 1
        print("conformance inventory present")
        return 0
    OUT.write_text(_full_document())
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
