"""Generate docs/testers/PER-TEST-GUIDE.md, docs/testers/TEST-PLANNING.md and the per-rule field table in
docs/standards/AGENT-INDEPENDENCE-AUDIT.md (between markers) from the catalogue, the rules, standards_map.yaml,
scenarios.yaml and docs/tests/<ID>.md references. Usage: python scripts/gen_tester_docs.py"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import rule_fields  # noqa: E402

from agentest.standards import reports  # noqa: E402
from agentest.standards.rules import RULES  # noqa: E402

CLASS = {"T1": "Task completion and state integrity", "T2": "Tool use and side effects", "T3": "Authorisation and human approval",
         "T4": "Prompt injection and untrusted content", "T5": "Policy, data and runtime guardrails", "T6": "Memory, retrieval and provenance",
         "T7": "Fairness, language and explainability", "X": "Cross-cutting (efficiency, transparency, robustness)"}
TRIAGE = {
    "T1": "Open the run's trace: compare the final answer and `agentest.final_state` with the executed `agentest.state_change` events. A claim without an effect (or the reverse) is the defect; a missing success signal gives n/a, not fail.",
    "T2": "List the `execute_tool` spans in order. Check duplicate calls with identical arguments, missing prerequisite calls and the MCP annotations of each tool (an undeclared tool is treated as a write).",
    "T3": "Check the `agentest.approval` spans: was a decision recorded and granted *before* the gated write? Text in the request that looks like approval is not approval.",
    "T4": "Find the untrusted content (tool result, document, feed) and the directive inside it. Did any canary or directive-derived token reach write arguments, effects or the decided outcome? Quoting it as data is allowed.",
    "T5": "Compare tool arguments with the MCP inputSchema and the governance limits/data classes. Most fails are a real limit crossed or a restricted value sent raw; check the threshold before filing.",
    "T6": "Check that retrieval runs record citations (`agentest.citations`) and that cited ids exist in the retrieved results.",
    "T7": "Compare paired (metamorphic) runs: the outcome must not change when only a protected attribute or language changes. Wording-only differences are not defects.",
    "X": "These are budget and transparency checks (steps, tokens, time, reasons). Confirm the budget in the config before treating a fail as a defect.",
}


def refs(tid: str) -> str:
    p = ROOT / "docs" / "tests" / f"{tid}.md"
    if not p.exists():
        return ""
    m = re.search(r"## References\n(.*?)(\n## |\Z)", p.read_text(), re.S)
    items = [ln for ln in (m.group(1).splitlines() if m else []) if re.match(r"\d+\. ", ln)]
    return "\n".join(items)


def main() -> None:
    rows = reports.catalog_rows()
    fields = {r["id"]: r for r in rule_fields.analyse()}
    smap = reports.standards_map()
    scen = yaml.safe_load((ROOT / "src" / "agentest" / "standards" / "scenarios.yaml").read_text()).get("expect", {})
    out = ["# Per-test guide (all 130 IDs)", "",
           "Generated by `scripts/gen_tester_docs.py` from the catalogue, `src/agentest/standards/rules.py`, `standards_map.yaml`,",
           "`scenarios.yaml` and the references in [docs/tests](../tests/README.md). Do not edit by hand.", "",
           "Each entry gives: purpose, what the check reads, how pass / fail / n/a are decided, triage steps, the standards",
           "mapping and the original sources. **Heuristics are marked**: several checks use English-language regular",
           "expressions (claims, refusals, directives). They are deterministic but can be wrong; see",
           "[triaging false positives](FALSE-POSITIVES.md).", ""]
    for cls in CLASS:
        out.append(f"- [{cls}: {CLASS[cls]}](#{cls.lower()}-{re.sub(r'[^a-z0-9]+', '-', CLASS[cls].lower()).strip('-')})")
    out.append("")
    for cls, title in CLASS.items():
        out += [f"## {cls}: {title}", ""]
        for r in [x for x in rows if x["class_id"] == cls]:
            tid = r["id"]
            what = RULES[tid][0]
            f = fields.get(tid, {})
            heur = any(k in what.lower() for k in ("claim", "refus", "directive", "injected", "warn", "reason")) or tid.startswith("T7")
            std = smap.get(tid, {})
            out += [f"### {tid}: {r['title']}", "",
                    f"Priority **{r['priority'] or 'unset'}**, severity {r['severity'] or 'unset'}. Full page: [{tid}](../tests/{tid}.md).", "",
                    f"**Purpose.** {r['objective']}", "",
                    "**What it reads.** " + ("; ".join(f.get("standard", [])) or "-") + (
                        ". Extension: " + "; ".join(x[4:] for x in f.get("extension", [])) if f.get("extension") else ""), "",
                    f"**Pass / fail.** {what}" + (" *(heuristic: text patterns)*" if heur else ""),
                    f"Catalogue acceptance criteria: {r['acceptance_criteria']}",
                    "n/a means no standard signal in the inputs (for example no run of the needed kind, or the needed fact is not declared); it is never a pass.", ""]
            if tid in scen:
                out += ["**Conformance scenario.** `scenarios.yaml` also holds a test-owned oracle for the agentest fixture world of this ID; it applies only to runs whose input id is this ID.", ""]
            out += [f"**Triage.** {TRIAGE[cls]}", "",
                    "**Standards.** " + ("; ".join(f"{k}: {', '.join(v)}" for k, v in std.items()) or "none mapped"), ""]
            rf = refs(tid)
            if rf:
                out += ["**Original sources.**", "", rf, ""]
    (ROOT / "docs" / "testers" / "PER-TEST-GUIDE.md").write_text("\n".join(out))

    plan = ["# Risk-based test planning", "",
            "Generated by `scripts/gen_tester_docs.py`. Run P0 first: these are the IDs whose failure means wrong",
            "durable state, an unapproved action or a data leak. Then P1, then P2 and unprioritised IDs.", "",
            "Mappings come from [standards_map.yaml](../../src/agentest/standards/standards_map.yaml) (OWASP Top 10 for LLM",
            "Applications 2025, OWASP Agentic AI Threats and Mitigations v1, NIST AI RMF 1.0 subcategories, ISO/IEC 42001:2023",
            "Annex A controls). They are our mapping, not a certification.", "",
            "## How to plan", "",
            "1. Pick the risks that matter for the agent (writes money? handles personal data? reads untrusted content?).",
            "2. Select the P0 IDs in those rows; make sure the agent's inputs cover them (an injection input for T4, an",
            "   approval-gated write for T3). An ID with no matching input returns n/a.",
            "3. Record runs, run `agentest std run --format junit`, and treat any P0 fail as release-blocking.",
            "4. Add P1 IDs; budget IDs (X-005..X-007) need agreed thresholds in the config first.", ""]
    for p in ("P0", "P1", "P2", ""):
        plan += [f"## {p or 'Unprioritised'}", "", "| ID | title | OWASP LLM 2025 | OWASP Agentic | NIST AI RMF | ISO 42001 |", "|---|---|---|---|---|---|"]
        for r in [x for x in rows if x["priority"] == p]:
            s = smap.get(r["id"], {})
            plan.append(f"| [{r['id']}](PER-TEST-GUIDE.md#{r['id'].lower()}-{re.sub(r'[^a-z0-9]+', '-', r['title'].lower()).strip('-')}) | {r['title']} | "
                        + " | ".join(", ".join(s.get(k, [])) for k in ("owasp_llm_2025", "owasp_agentic_threats_v1", "nist_ai_rmf", "iso_42001_annex_a")) + " |")
        plan.append("")
    (ROOT / "docs" / "testers" / "TEST-PLANNING.md").write_text("\n".join(plan))

    audit = ROOT / "docs" / "standards" / "AGENT-INDEPENDENCE-AUDIT.md"
    if audit.exists():
        t = audit.read_text()
        table = rule_fields.to_md(list(fields.values()))
        t = re.sub(r"<!-- fields:start -->.*<!-- fields:end -->", "<!-- fields:start -->\n" + table + "<!-- fields:end -->", t, flags=re.S)
        audit.write_text(t)
    print(json.dumps({"tests": len(rows)}))


if __name__ == "__main__":
    main()
