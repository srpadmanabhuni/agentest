#!/usr/bin/env python3
"""OpenTelemetry GenAI compatibility matrix: render docs/integrations/otel-genai-compatibility.md and keep it honest.

The hand-kept source is docs/integrations/otel-genai-matrix.json (one row per operation, span type, event, message part
and attribute of the pinned GenAI conventions). The "Checks" column is computed: each row names the per-check fields of
scripts/rule_fields.py it feeds, and this script turns them into check IDs.

  python scripts/otel_genai_matrix.py --write                       # regenerate the page
  python scripts/otel_genai_matrix.py --check                       # offline: page current, pin consistent, rows resolve
  python scripts/otel_genai_matrix.py --check --semconv-dir DIR     # also: every item of the pinned model has a row

DIR is a checkout of the GenAI repository at the pinned commit (CI fetches that commit). The conventions are in
Development status, so the pin is a commit SHA, not a version.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MATRIX = ROOT / "docs" / "integrations" / "otel-genai-matrix.json"
PAGE = ROOT / "docs" / "integrations" / "otel-genai-compatibility.md"
SEMCONV = ROOT / "src" / "agentest" / "standards" / "semconv.yaml"
SOURCES = [ROOT / "src" / "agentest" / "standards" / n for n in ("otel.py", "rules.py", "semconv.yaml")] + sorted(
    (ROOT / "src" / "agentest" / "standards" / "new_tests").glob("*.py"))
STATUS = {"read": "read", "partial": "partial", "not-read": "not read"}
KINDS = [("operation", "Operations (`gen_ai.operation.name`)"), ("span", "Span types"), ("event", "Events"),
         ("part", "Message parts (`gen_ai.input.messages`, `gen_ai.output.messages`)"), ("attribute", "Attributes"),
         ("metric", "Metrics")]
LIST_UP_TO = 6


def load() -> dict:
    return json.loads(MATRIX.read_text(encoding="utf-8"))


def rule_fields() -> list[dict]:
    spec = importlib.util.spec_from_file_location("rule_fields", ROOT / "scripts" / "rule_fields.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.analyse()


def checks_by_field(rows: list[dict]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for r in rows:
        for f in r["fields"]:
            out.setdefault(f, []).append(r["id"])
    return out


def row_checks(row: dict, by_field: dict[str, list[str]]) -> list[str]:
    ids = {i for f in row.get("uses") or [] for i in by_field.get(f, [])}
    return sorted(ids)


def counts(rows: list[dict]) -> dict[str, dict[str, int]]:
    out = {k: {"read": 0, "partial": 0, "not-read": 0} for k, _ in KINDS}
    for r in rows:
        out[r["kind"]][r["status"]] += 1
    return out


def render(m: dict, fields: list[dict]) -> str:
    rows, by_field = m["rows"], checks_by_field(fields)
    pin, sc = m["pinned"], yaml.safe_load(SEMCONV.read_text(encoding="utf-8"))
    n = counts(rows)
    tot = {s: sum(v[s] for v in n.values()) for s in STATUS}
    L = ["# OpenTelemetry GenAI compatibility matrix", "",
         "<!-- Generated by scripts/otel_genai_matrix.py from otel-genai-matrix.json. Do not edit by hand. -->", "",
         "**AiEnsured agentest, an Agentic AI Testing platform** judges what an agent did from its OpenTelemetry traces. "
         "The OpenTelemetry GenAI semantic conventions are in *Development* status and change often, so this page lists, "
         "for one pinned version of them, what agentest reads, what it reads only in part, and what it does not read.", "",
         "```bash", "pip install agentest-ai", "```", "",
         "Nothing here is an endorsement by OpenTelemetry or by any framework; it is a statement about what agentest's importer does.", "",
         "## What this page is pinned to", "",
         f"- GenAI conventions repository: <{pin['repo']}>",
         f"- Commit: `{pin['commit']}` (a checkout of the model at this commit is what `--semconv-dir` verifies the rows against)",
         f"- Release tag at or before that commit: `{pin['release']}`",
         f"- Schema version agentest declares and reports: `{sc['pinned']['semconv']}` (`{sc['pinned']['schema_url']}`); traces that declare an "
         "older version are mapped onto the current names (see [Earlier conventions](#earlier-conventions-mapped-onto-the-current-names)).",
         "- Stability of every attribute in the pinned model: Development.", "",
         "## How to read the table", "",
         "- **read**: the importer maps the item into the run and at least one of the 130 default checks uses it, or the importer relies on it to structure the run.",
         "- **partial**: read only in some forms or positions, or used only by opt-in rules.",
         "- **not read**: no check interprets it. Every span attribute value still counts toward the leak scans, whether or not the row says *read*.",
         "- **Checks**: the default checks that use the item, from `scripts/rule_fields.py` (the 130 default IDs only; opt-in packs and new tests are not counted unless the row says so).", "",
         "## Coverage", "", "| Kind | Rows | read | partial | not read |", "|---|---|---|---|---|"]
    for k, title in KINDS:
        v = n[k]
        L.append(f"| {title.split(' (')[0]} | {sum(v.values())} | {v['read']} | {v['partial']} | {v['not-read']} |")
    L += [f"| **All** | **{sum(tot.values())}** | **{tot['read']}** | **{tot['partial']}** | **{tot['not-read']}** |", ""]
    for k, title in KINDS:
        L += [f"## {title}", "", "| Name | Status | What agentest does | Checks |", "|---|---|---|---|"]
        for r in (x for x in rows if x["kind"] == k):
            ids = row_checks(r, by_field)
            cell = "-" if not ids else (", ".join(ids) if len(ids) <= LIST_UP_TO else f"{len(ids)} checks ([list](#checks-per-field))")
            L.append(f"| `{r['name']}` | {STATUS[r['status']]} | {r['how']} | {cell} |")
        L.append("")
    L += ["## Earlier conventions mapped onto the current names", "",
          "`src/agentest/standards/semconv.yaml` holds the tables. A name already present on a span is never overwritten.", "",
          "| Style | Convention versions | Renamed to the current name |", "|---|---|---|"]
    for name, st in sc["styles"].items():
        if not st.get("versions"):
            continue
        ren = ", ".join(f"`{a}` → `{b}`" for a, b in (st.get("rename") or {}).items()) or "-"
        L.append(f"| `{name}` | {', '.join(st['versions'])} | {ren} |")
    L += ["", "Two other instrumentation styles (not OpenTelemetry versions) are mapped by the same file; see `semconv.yaml`."]
    L += ["", "## Checks per field", "",
          "The fields below are named in `scripts/rule_fields.py`; each lists the default checks that read it.", ""]
    used = sorted({f for r in rows for f in r.get("uses") or []})
    for f in used:
        L += [f"- **{f}** ({len(by_field.get(f, []))}): {', '.join(by_field.get(f, []))}"]
    L += ["", "## Tested with the official instrumentation", "",
          "`tests/test_otel_genai_instrumentation.py` emits one run with the OpenTelemetry GenAI instrumentation library "
          "(`opentelemetry-util-genai`, pre-release) in all three content-capture modes (`SPAN_ONLY`, `EVENT_ONLY`, `SPAN_AND_EVENT`) "
          "and requires the same verdicts as the hand-written trace of the same behaviour. CI installs the library when it can "
          "(`pip install --pre opentelemetry-util-genai`) and then fails, rather than skips, if the test does not run.", "",
          "## Gaps filled since 3.7.0", "",
          "- Structured tool results (an OTLP key-value list) are kept as JSON text instead of a Python repr; a non-object tool-argument value no longer raises.",
          "- Content recorded on `gen_ai.client.inference.operation.details` (span event or log record) is merged onto its span.",
          "- `gen_ai.execute_tool.transfer` spans (`gen_ai.transfer.target.name`) are read as handoffs.",
          "- `realtime_inference` is read as a model call.",
          "- `gen_ai.workflow.name` and `gen_ai.usage.cache_creation.input_tokens` (names replaced upstream) are mapped to their successors.", "",
          "## Not covered", "",
          "- OpenTelemetry metrics and the MCP and A2A semantic-convention pages: agentest judges traces, and reads MCP tool facts from `tools.json`.",
          "- Content stored outside the trace (the `*_ref` attributes): agentest sees only the reference.",
          "- Provider-specific attributes.", "",
          "## Keeping this page current", "",
          "```bash", "python scripts/otel_genai_matrix.py --check",
          f"git clone https://github.com/open-telemetry/semantic-conventions-genai /tmp/genai && git -C /tmp/genai checkout {pin['commit']}",
          "python scripts/otel_genai_matrix.py --check --semconv-dir /tmp/genai", "```", "",
          "CI runs both. To move the pin, check out the newer commit, run the second command, add or change the rows it reports, "
          "update `genai_commit` in `semconv.yaml` and the `commit` in `otel-genai-matrix.json`, then run `--write`.", ""]
    return "\n".join(L)


# ---------------------------------------------------------------- model of the pinned conventions

EXTERNAL = ("error.", "server.", "exception.", "process.")


def model_items(d: Path) -> dict[str, set[str]]:
    base = d / "model" / "gen-ai"
    reg = yaml.safe_load((base / "registry.yaml").read_text(encoding="utf-8"))
    spans = yaml.safe_load((base / "spans.yaml").read_text(encoding="utf-8"))
    events = yaml.safe_load((base / "events.yaml").read_text(encoding="utf-8"))
    groups: dict[str, dict] = {}
    for p in base.glob("*.yaml"):
        for g in yaml.safe_load(p.read_text(encoding="utf-8")).get("attribute_groups") or []:
            groups[g["id"]] = g

    def refs(attrs, out: set) -> None:
        for a in attrs or []:
            if "ref_group" in a:
                refs(groups[a["ref_group"]]["attributes"], out)
            elif "ref" in a:
                out.add(a["ref"])

    used: set[str] = set()
    for x in (spans.get("spans") or []) + (spans.get("span_refinements") or []) + (events.get("events") or []):
        refs(x.get("attributes"), used)
    attrs = {a["key"] for a in reg["attributes"]} | {u for u in used if u.startswith(EXTERNAL)}
    ops = {m["value"] for a in reg["attributes"] if a["key"] == "gen_ai.operation.name" for m in a["type"]["members"]}
    sp = {s["type"] for s in spans["spans"]} | {r["id"] for r in spans.get("span_refinements") or [] if r["id"].startswith("gen_ai.")}
    ev = {e["name"] for e in events["events"]}
    parts: set[str] = set()
    for f in ("input", "output"):
        schema = json.loads((base / f"gen-ai-{f}-messages.json").read_text(encoding="utf-8"))
        for v in (schema.get("$defs") or schema.get("definitions") or {}).values():
            c = ((v.get("properties") or {}).get("type") or {}).get("const")
            if c:
                parts.add(c)
    return {"attribute": attrs, "operation": ops, "span": sp, "event": ev, "part": parts}


GROUP_ROWS = {"provider-specific attributes (vendor-prefixed, from the provider refinements)", "provider-specific refinements",
              "generic (provider-specific part)", "gen_ai.* metrics (client, server, agent and token metrics)"}


def check_model(m: dict, d: Path) -> list[str]:
    errs: list[str] = []
    head = subprocess.run(["git", "-C", str(d), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    if head != m["pinned"]["commit"]:
        errs.append(f"--semconv-dir is at {head or 'no git checkout'}, the matrix is pinned to {m['pinned']['commit']}")
    want = model_items(d)
    have: dict[str, set[str]] = {k: set() for k, _ in KINDS}
    for r in m["rows"]:
        have[r["kind"]].add(r["name"])
    for k, items in want.items():
        for n in sorted(items - have[k]):
            errs.append(f"model has {k} `{n}`, the matrix has no row for it")
        for n in sorted(have[k] - items - GROUP_ROWS):
            errs.append(f"matrix row {k} `{n}` is not in the pinned model")
    return errs


def check(m: dict, fields: list[dict], semconv_dir: Path | None) -> list[str]:
    errs: list[str] = []
    sc = yaml.safe_load(SEMCONV.read_text(encoding="utf-8"))
    if m["pinned"]["commit"] != sc["pinned"]["genai_commit"]:
        errs.append("pinned commit differs between otel-genai-matrix.json and semconv.yaml")
    if m["pinned"]["release"] != sc["pinned"].get("genai_release"):
        errs.append("pinned release differs between otel-genai-matrix.json and semconv.yaml")
    known = {f for r in fields for f in r["fields"]}
    seen: set[tuple[str, str]] = set()
    text = "\n".join(p.read_text(encoding="utf-8") for p in SOURCES)
    for r in m["rows"]:
        key = (r["kind"], r["name"])
        if key in seen:
            errs.append(f"duplicate row {key}")
        seen.add(key)
        if r["status"] not in STATUS or r["kind"] not in dict(KINDS):
            errs.append(f"bad status or kind in {key}")
        for f in r.get("uses") or []:
            if f not in known:
                errs.append(f"{key}: `uses` names a field no check reads: {f!r}")
        if r["kind"] == "attribute" and r["status"] != "not-read" and r["name"] not in text:
            errs.append(f"{key} is marked {r['status']} but the importer and checks never mention it")
        if r["status"] != "not-read" and r["kind"] in ("attribute", "operation") and not r.get("uses") and r["status"] == "read" \
                and r["name"] not in text:
            errs.append(f"{key} is marked read but is not in the importer")
    if PAGE.read_text(encoding="utf-8") != render(m, fields):
        errs.append("docs/integrations/otel-genai-compatibility.md is out of date: run `python scripts/otel_genai_matrix.py --write`")
    if semconv_dir:
        errs += check_model(m, semconv_dir)
    return errs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--semconv-dir", type=Path)
    a = ap.parse_args()
    m, fields = load(), rule_fields()
    if a.write:
        PAGE.write_text(render(m, fields), encoding="utf-8")
        print(f"wrote {PAGE.relative_to(ROOT)}")
    if a.check or not a.write:
        errs = check(m, fields, a.semconv_dir)
        for e in errs:
            print("ERROR:", e, file=sys.stderr)
        n = counts(m["rows"])
        tot = {s: sum(v[s] for v in n.values()) for s in STATUS}
        print(f"rows {sum(tot.values())}: read {tot['read']}, partial {tot['partial']}, not read {tot['not-read']}")
        return 1 if errs else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
