#!/usr/bin/env python3
"""Rewrite ``[tool.setuptools.data-files]`` in pyproject.toml from the bundled data (catalogue, agents, baseline).

Every agent folder under ``agents/`` ships its three standard files: ``agent-card.json``, ``tools.json`` and
``traces/*``. ``tests/test_packaging.py`` fails if this table is out of date. Usage: python scripts/gen_data_files.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def table() -> str:
    lines = ["[tool.setuptools.data-files]",
             '"share/agentest/catalog" = ["catalog/*.csv", "catalog/*.jsonl", "catalog/VERSION", "catalog/*.yaml"]',
             '"share/agentest/fixtures/standards" = ["fixtures/standards/*.json"]']
    for d in sorted(p for p in (ROOT / "agents").iterdir() if p.is_dir()):
        a = d.name
        lines.append(f'"share/agentest/agents/{a}" = ["agents/{a}/agent-card.json", "agents/{a}/tools.json"]')
        lines.append(f'"share/agentest/agents/{a}/traces" = ["agents/{a}/traces/*"]')
    return "\n".join(lines) + "\n"


def main() -> None:
    p = ROOT / "pyproject.toml"
    s = p.read_text()
    s = re.sub(r"(?:# [^\n]*\n)?\[tool\.setuptools\.data-files\]\n(?:[^\[\n][^\n]*\n|\n)*",
               "# Bundled data located by agentest.paths.root() after a wheel install (generated by scripts/gen_data_files.py).\n"
               + table() + "\n", s, count=1)
    p.write_text(s)


if __name__ == "__main__":
    main()
