"""Coverage of the 130 catalogue IDs on the reference agents (agents/aNN), in both modes.

For every ID: on how many reference agents it is *decided* (pass or fail, not n/a), and how many of those are
passes and fails. Writes docs/COVERAGE.md; ``--check`` exits non-zero when the checked-in file is stale (CI).
Only the published standard inputs are read (agent-card.json, tools.json, traces/*.otlp.jsonl).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from agentest.standards import metadata, runner  # noqa: E402
from agentest.standards.catalog import ALL_IDS  # noqa: E402

OUT = ROOT / "docs" / "COVERAGE.md"
BUCKETS = (("0", 0, 0), ("1-9", 1, 9), ("10-49", 10, 49), ("50-69", 50, 69), ("70+", 70, 10**6))


def compute() -> tuple[list[str], dict]:
    agents = {k: a for k, a in metadata.load_all().items() if re.fullmatch(r"a\d{2,3}", k)}
    res = {m: runner.run_all(agents, mode=m) for m in ("strict", "examples")}
    tab = {m: {i: (sum(1 for row in res[m].values() if row[i].status == "pass"), sum(1 for row in res[m].values() if row[i].status == "fail"))
               for i in ALL_IDS} for m in res}
    return sorted(agents), tab


def render(names: list[str], tab: dict) -> str:
    def bucket(m):
        cnt = {b: 0 for b, _, _ in BUCKETS}
        for p, f in tab[m].values():
            n = p + f
            cnt[next(b for b, lo, hi in BUCKETS if lo <= n <= hi)] += 1
        return cnt
    bs = {m: bucket(m) for m in tab}
    lines = ["# Catalogue coverage on the reference agents", "",
             f"Generated by `python scripts/coverage_table.py` from {len(names)} reference agents ({names[0]}-{names[-1]}) under `agents/`. "
             "CI runs `--check` so this file never drifts from the rules.", "",
             "A test is *decided* on an agent when its universal rule returns pass or fail (not n/a) from that agent's AgentCard, "
             "MCP tool list and OTel traces.", "", "## Buckets (number of agents a test is decided on)", "",
             "| mode | " + " | ".join(b for b, _, _ in BUCKETS) + " |", "|---|" + "---|" * len(BUCKETS)]
    lines += [f"| {m} | " + " | ".join(str(bs[m][b]) for b, _, _ in BUCKETS) + " |" for m in ("strict", "examples")]
    one_sided = [i for i in ALL_IDS if not (tab["examples"][i][0] and tab["examples"][i][1])]
    lines += ["", "## Per test", "", "| ID | strict decided (pass/fail) | examples decided (pass/fail) |", "|---|---|---|"]
    for i in ALL_IDS:
        (sp, sf), (ep, ef) = tab["strict"][i], tab["examples"][i]
        lines.append(f"| {i} | {sp + sf} ({sp}/{sf}) | {ep + ef} ({ep}/{ef}) |")
    lines += ["", f"## Tests without both a pass and a fail (examples mode): {len(one_sided)}", "",
              ", ".join(f"{i} ({'pass only' if tab['examples'][i][0] else 'fail only' if tab['examples'][i][1] else 'undecided'})" for i in one_sided) or "none", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if docs/COVERAGE.md is out of date")
    a = ap.parse_args()
    text = render(*compute())
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/COVERAGE.md is stale: run python scripts/coverage_table.py", file=sys.stderr)
            return 1
        print("coverage table up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
