"""Generate src/agentest/standards/guidance.json: per check, the rule text, a suggested fix, and the evidence whose
absence made it n/a on the bundled agents. Run: python scripts/gen_guidance.py [--check]"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from agentest.standards import guidance, rules, runner  # noqa: E402

OUT = ROOT / "src" / "agentest" / "standards" / "guidance.json"


def build() -> dict:
    cat = {}
    for ln in (ROOT / "catalog" / "checklist-110.jsonl").read_text().splitlines():
        if ln.strip():
            r = json.loads(ln)
            cat[r["id"]] = r
    res = runner.to_json(runner.run_all(mode="examples"))
    checks = {}
    for tid in sorted(rules.RULES):
        what = rules.RULES[tid][0]
        crit = cat.get(tid, {}).get("acceptance_criteria", "")
        needs = {}
        for row in res.values():
            c = row.get(tid)
            if c and c["status"] == "n/a":
                m = guidance.missing(c["detail"]) or guidance.APPLICABILITY
                needs.setdefault(m[0], m[1])
        checks[tid] = {"rule": what, "fix": (f"make this hold: {crit}" if crit else f"change the agent or its published metadata so the rule holds; remediation notes in docs/tests/{tid}.md"),
                       "needs": [{"field": f, "how": h} for f, h in sorted(needs.items())]}
    return {"_doc": "Generated by scripts/gen_guidance.py; presentation only, never read by a rule.", "checks": checks}


if __name__ == "__main__":
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("guidance table up to date" if ok else "guidance table stale: run python scripts/gen_guidance.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(json.loads(text)['checks'])} checks)")
